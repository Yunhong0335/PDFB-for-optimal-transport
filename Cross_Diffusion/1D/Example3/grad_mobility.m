function [m1, m2] = grad_mobility(u)
    m11 = u(:, 1).^2;
    m12 = u(:, 1).^2/2 + u(:, 1).* (u(:, 2) - u(:, 1));
    m22 = -(u(:, 2) - u(:, 1)).^2 + u(:, 1).^2 + u(:, 2) .* (u(:, 2) - u(:, 1)) - u(:, 1) .* u(:, 2);
    m1 = [m11, m12, m12, m22];
    
    m11 = zeros(size(u(:, 1)));
    m12 = u(:, 1).^2/2;
    m22 = (u(:, 2) - u(:, 1)).^2 + u(:, 1) .* (u(:, 2) - u(:, 1)) + u(:, 1) .* u(:, 2);
    m2 = [m11, m12, m12, m22];
end